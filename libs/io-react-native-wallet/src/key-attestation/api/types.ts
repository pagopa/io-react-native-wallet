import * as z from "zod";

import type { Signer } from "../../utils/crypto";

import { JWK } from "../../utils/jwk";
import { UnixTime } from "../../utils/zod";

const Status = z.object({
  status_list: z.object({
    idx: z.number(),
    uri: z.string(),
  }),
});

/**
 * Common Key Attestation shape. This object is
 * an abstraction over the version-specific JWTs.
 */
export type DecodedKeyAttestation = z.infer<typeof DecodedKeyAttestation>;
export const DecodedKeyAttestation = z.object({
  attested_keys: z.array(JWK),
  exp: UnixTime,
  iat: UnixTime,
  iss: z.string(),
  key_storage: z.array(z.string()),
  status: Status,
  user_authentication: z.array(z.string()),
});

/**
 * A key to include in the Key Attestation request.
 * The key must already exist: it is generated by the consumer using the challenge
 * obtained with `KeyAttestation.getChallenge`.
 */
export interface KeyToAttest {
  /**
   * The Android key attestation (certificate chain) generated with the challenge,
   * proving the key pair is hardware-backed. Required on Android, ignored elsewhere.
   */
  attestation?: string;
  /** The signer bound to the key to attest. */
  signer: Signer;
}

export interface WalletAttestation {
  attestation: string;
  format: string;
}

export interface WalletAttestationRequestParams {
  walletProviderBaseUrl: string;
  walletSolutionId: string;
  walletSolutionVersion: string;
}
