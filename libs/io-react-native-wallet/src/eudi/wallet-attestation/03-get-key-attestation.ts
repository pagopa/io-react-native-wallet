import { SignJWT, thumbprint } from "@pagopa/io-react-native-jwt";
import { Platform } from "react-native";

import type { KeyAttestationCryptoContext } from "../../utils/crypto";
import type { IntegrityContext } from "../../utils/integrity";

import { getWalletProviderClient } from "../../client";
import { IoWalletError } from "../../utils/errors";
import { fixBase64EncodingOnKey, JWK } from "../../utils/jwk";
import { Logger, LogLevel } from "../../utils/logging";
import {
  KeyAttestationResponse,
  type WalletAttestationRequestParams,
} from "./types";
import { postToWalletProvider } from "./utils";

/**
 * Generate the key to attest and build its Key Attestation Request, signed with the key itself.
 */
const createKeyAttestationRequest = async (
  challenge: string,
  cryptoContext: KeyAttestationCryptoContext,
) => {
  const { attestation, success } =
    await cryptoContext.generateKeyWithAttestation(challenge);

  if (!success) {
    throw new IoWalletError(
      "generateKeyWithAttestation failed to generate a cryptographic key for the Key Attestation request",
    );
  }

  if (Platform.OS === "android" && !attestation) {
    throw new IoWalletError(
      "Missing Android key attestation: the generated key pair must be hardware-backed",
    );
  }

  const publicKey = JWK.parse(await cryptoContext.getPublicKey());

  const keyAttestationRequestJwt = await new SignJWT(cryptoContext)
    .setPayload({
      cnf: {
        jwk: fixBase64EncodingOnKey(publicKey),
      },
      wscd_key_attestation: {
        storage_type: "LOCAL_NATIVE",
        ...(attestation && { attestation }),
      },
    })
    .setProtectedHeader({
      kid: publicKey.kid,
      typ: "key-attestation-request+jwt",
    })
    .setIssuedAt()
    .setExpirationTime("1h")
    .sign();

  return { cryptoContext, keyAttestationRequestJwt, publicKey };
};

/**
 * Request a Key Attestation to the EUDI Wallet Provider for one or more keys, generated by this call.
 * The Credential Issuers receive it in the proof of possession of the credential key (HAIP, Section 4.5.1).
 * Copy of the IT-Wallet v1.4.6 implementation, kept separate to evolve with the EUDI Wallet Provider.
 *
 * @param requestParams Wallet Provider data for the Key Attestation request
 * @param ctx.keysToAttest The keys to generate and attest, the first one signs the request
 * @param ctx.integrityContext The hardware key pair associated with the Wallet Instance
 * @param ctx.appFetch (optional) Http client
 * @returns The Key Attestation in JWT format
 * @throws {WalletProviderResponseError} with a specific code for more context
 */
export const getKeyAttestation = async (
  requestParams: WalletAttestationRequestParams,
  {
    appFetch = fetch,
    integrityContext,
    keysToAttest: keysToAttestContexts,
  }: {
    appFetch?: typeof fetch;
    integrityContext: IntegrityContext;
    keysToAttest: KeyAttestationCryptoContext[];
  },
): Promise<string> => {
  const { walletProviderBaseUrl, walletSolutionId, walletSolutionVersion } =
    requestParams;
  const api = getWalletProviderClient({ appFetch, walletProviderBaseUrl });

  const { nonce } = await api.get("/nonce");
  Logger.log(
    LogLevel.DEBUG,
    `Challenge obtained from ${walletProviderBaseUrl}: ${nonce}`,
  );

  const keysToAttest = await Promise.all(
    keysToAttestContexts.map((cryptoContext) =>
      createKeyAttestationRequest(nonce, cryptoContext),
    ),
  );

  const [signatureKey] = keysToAttest;
  if (!signatureKey) {
    throw new IoWalletError("At least one key to attest must be provided");
  }

  const hardwareKeyTag = integrityContext.getHardwareKeyTag();

  const clientData = {
    challenge: nonce,
    jwk_thumbprints: await Promise.all(
      keysToAttest.map((k) => thumbprint(k.publicKey)),
    ),
  };

  const { authenticatorData, signature } =
    await integrityContext.getHardwareSignatureWithAuthData(
      JSON.stringify(clientData),
    );

  const signedAttestationRequest = await new SignJWT(signatureKey.cryptoContext)
    .setPayload({
      cnf: {
        jwk: fixBase64EncodingOnKey(signatureKey.publicKey),
      },
      hardware_key_tag: hardwareKeyTag,
      hardware_signature: signature,
      integrity_assertion: authenticatorData,
      iss: hardwareKeyTag,
      keys_to_attest: keysToAttest.map((k) => k.keyAttestationRequestJwt),
      nonce,
      platform: Platform.OS,
      wallet_solution_id: walletSolutionId,
      wallet_solution_version: walletSolutionVersion,
    })
    .setProtectedHeader({
      kid: signatureKey.publicKey.kid,
      typ: "wua-request+jwt",
    })
    .setIssuedAt()
    .setExpirationTime("1h")
    .sign();

  Logger.log(
    LogLevel.DEBUG,
    `Signed key attestation request: ${signedAttestationRequest}`,
  );

  const response = await postToWalletProvider(
    walletProviderBaseUrl,
    "/ka",
    signedAttestationRequest,
    appFetch,
  ).then(KeyAttestationResponse.parse);

  Logger.log(
    LogLevel.DEBUG,
    `Obtained Key Attestation: ${response.key_attestation}`,
  );

  return response.key_attestation;
};
